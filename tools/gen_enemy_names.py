"""Writes src/enemy_names.h, the display names Bounty Hunter may show for a wanted enemy.

    python3 tools/gen_enemy_names.py <rac2-decomp>/docs/game/moby-dispatch.tsv [--check]

The names are the community class labels that rac2-decomp's moby-dispatch.tsv cites for each moby
class (Replanetizer's MobyModelsRC2.txt and Wrench's gc_moby_classes asset; the URL of each is in
the table). They are names only: no text, data or code of the game. A class with no cited label has
no name here, and the mod shows it as an unidentified hostile rather than inventing one.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "enemy_names.h"


def generate(tsv: Path) -> str:
    names: dict[int, tuple[str, str]] = {}
    with tsv.open(newline="") as f:
        for row in csv.DictReader(f, delimiter="\t"):
            if row.get("table") != "moby" or not row.get("class_label"):
                continue
            cid = int(row["id"])
            label = row["class_label"].strip()
            if not label.isascii() or any(c in label for c in '"\\'):
                continue
            names.setdefault(cid, (label, row.get("class_label_basis", "")))
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/gen_enemy_names.py from rac2-decomp docs/game/moby-dispatch.tsv. Do not edit.",
        "// Community class labels (Replanetizer, Wrench), cited per class in that table.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace bounty_hunter {",
        "",
        "struct EnemyName {",
        "    std::int32_t moby_class;",
        "    const char* name;",
        "};",
        "",
        "// clang-format off",
        "inline constexpr EnemyName kEnemyNames[] = {",
    ]
    for cid in sorted(names):
        lines.append(f'    {{{cid}, "{names[cid][0]}"}},')
    lines += [
        "};",
        "// clang-format on",
        "",
        "// Returns the cited name of `moby_class`, or nullptr when the table has none.",
        "inline const char* enemy_name(std::int32_t moby_class) {",
        "    for (const EnemyName& entry : kEnemyNames) {",
        "        if (entry.moby_class == moby_class) {",
        "            return entry.name;",
        "        }",
        "    }",
        "    return nullptr;",
        "}",
        "",
        "}  // namespace bounty_hunter",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    text = generate(Path(sys.argv[1]))
    if "--check" in sys.argv[2:]:
        if OUT.read_text() != text:
            print(f"{OUT} differs: run tools/gen_enemy_names.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
